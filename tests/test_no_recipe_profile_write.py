"""A recipe never writes into xlings' shell profile (xlings design 2026-11-27 §20.2).

`config/shell/xlings-profile.{sh,fish,ps1}` is generated by xlings and
rewritten when it is upgraded: a block a package put there was lost at the next
upgrade, stayed with the version that last ran `config()` instead of following
`xlings use`, and every package that did it carried its own generation,
insertion and removal. A program's shell completion is declared instead --

    xvm.add("tool", { bindir = ..., completion = { bash = "...", zsh = "...",
                                                   fish = "...", pwsh = "..." } })

-- (libxpkg 0.0.68): each file is linked into the SubOS where its shell looks,
follows `xlings use`, goes with the version, and xlings' profile loads it.
"""
import glob
import os

import pytest

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def _files():
    return sorted(glob.glob(os.path.join(ROOT, "pkgs", "**", "*.lua"), recursive=True)
                  + glob.glob(os.path.join(ROOT, "libs", "*.lua")))


@pytest.mark.static
@pytest.mark.parametrize("recipe", _files(), ids=lambda p: os.path.relpath(p, ROOT))
def test_a_recipe_does_not_write_the_xlings_profile(recipe):
    bad = []
    with open(recipe, encoding="utf-8") as f:
        for n, line in enumerate(f, 1):
            if "xlings-profile" in line:
                bad.append(f"{n}: {line.strip()}")
    assert not bad, (
        "a recipe names xlings' shell profile, which xlings rewrites at its upgrades; declare the "
        "program's shell completion on xvm.add(name, { completion = { ... } }) instead:\n  "
        + "\n  ".join(bad))
