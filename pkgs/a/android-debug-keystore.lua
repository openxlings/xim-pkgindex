import("xim.libxpkg.pkginfo")
import("xim.libxpkg.xvm")
import("xim.libxpkg.log")

function install()
    -- The download IS the file: no archive, nothing to extract. Same shape
    -- pkgs/b/bazel.lua uses for its own single-file payload.
    os.tryrm(pkginfo.install_dir())
    os.mkdir(pkginfo.install_dir())

    local dest = path.join(pkginfo.install_dir(), "debug.keystore")
    os.mv(pkginfo.install_file(), dest)

    if not os.isfile(dest) then
        raise("android-debug-keystore: " .. dest .. " was not written")
    end

    log.debug("android-debug-keystore: wrote %s", dest)
    return true
end

function config()
    -- Umbrella only: this package provides a data file, not a program, so
    -- there is no `bin/<name>` to shim -- the same `type = "group"` idiom
    -- `android-ndk.lua` and `pkgs/a/android-platform.lua` both use for a
    -- payload with nothing to dispatch. A consumer (`dist-apk`) reaches the
    -- file with `pkginfo.dep_install_dir("xim:android-debug-keystore")` and
    -- joins `"debug.keystore"` itself, never through a shim or PATH.
    xvm.add(package.name, { type = "group" })
    return true
end

function uninstall()
    xvm.remove(package.name)
    return true
end
